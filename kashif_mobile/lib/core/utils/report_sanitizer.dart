final RegExp _refRe = RegExp(r'\$(\d)');
final Map<String, RegExp> _rxCache = <String, RegExp>{};

/// Compiles each pattern once; the sanitizer runs on every parsed string.
RegExp _rx(String pattern, {bool caseSensitive = true}) =>
    _rxCache.putIfAbsent('$caseSensitive|$pattern',
        () => RegExp(pattern, caseSensitive: caseSensitive));

extension _Sub on String {
  /// Like replaceAll, but expands $1..$9 group references in [template]
  /// (Dart's String.replaceAll with a RegExp does not).
  String sub(RegExp pattern, String template) =>
      replaceAllMapped(pattern, (m) {
        return template.replaceAllMapped(_refRe, (g) {
          final i = int.parse(g.group(1)!);
          return i <= m.groupCount ? (m.group(i) ?? '') : '';
        });
      });
}

/// Utility to clean and sanitize any scanner device brand names (Ediag, Launch, etc.)
/// and strictly enforce authentic Libyan workshop terms across the entire app.
class ReportSanitizer {
  static String clean(String? input) {
    if (input == null || input.isEmpty) return '';

    String text = input
        .replaceAll(
          _rx(r'بواسطة\s+جهاز\s+(كشف|فحص)\s+[A-Za-z0-9_\-]+', caseSensitive: false),
          'عبر الفحص الإلكتروني الشامل',
        )
        .replaceAll(
          _rx(r'بجهاز\s+(كشف|فحص)\s+[A-Za-z0-9_\-]+(\s+بدون\s+إنترنت)?', caseSensitive: false),
          'عبر الفحص الإلكتروني الشامل',
        )
        .replaceAll(
          _rx(r'تقرير\s+جهاز\s+[A-Za-z0-9_\-]+', caseSensitive: false),
          'تقرير الفحص الإلكتروني',
        )
        .replaceAll(
          _rx(r'جهاز\s+(كشف|فحص)\s+(Ediag|Launch|Autel|Thinkdiag|G-Scan|OBD)', caseSensitive: false),
          'جهاز الفحص',
        )
        .replaceAll(
          _rx(r'\(Ediag\s+أو\s+ما\s+يعادله\)', caseSensitive: false),
          'بجهاز الفحص المعتمد',
        )
        .replaceAll(
          _rx(r'Ediag|Thinkdiag|Autel|Launch', caseSensitive: false),
          '',
        )
        .replaceAll('تفتفة', 'فطفطة')
        .replaceAll(
          _rx(r'خطوات\s+فحص\s+الأ?سطى\s+والورشة|خطوات\s+فحص\s+الأ?سطى|فحص\s+الأ?سطى', caseSensitive: false),
          'خطوات الفحص الفني والورشة',
        )
        .sub(_rx(r'الأ?سطى', caseSensitive: false), 'الفني');

    return applyTerms(text).sub(_rx(r'\s{2,}'), ' ').trim();
  }

  /// Pure terminology pass (no whitespace changes), so it is also safe to run
  /// over multi-line text and source files.
  /// Rules follow قاموس_مصطلحات_صيانة_السيارات_الليبية.md.
  static String applyTerms(String input) {
    String text = input;

    // Arabic letter boundary helper:
    // (?<![\u0621-\u0647\u0649\u064A]) ensures not preceded by an Arabic letter
    // (?![\u0621-\u064A]) ensures not followed by an Arabic letter

    // 1. Transmission: قير / جير / فتيس / ناقل حركة -> كمبيو
    text = text
        .sub(_rx(r'ناقل\s+الحركة\s+الأوتوماتيكي?'), 'الكمبيو الأوتوماتيك')
        .sub(_rx(r'ناقل\s+الحركة\s+العادي?|ناقل\s+الحركة\s+اليدوي?'), 'الكمبيو العادي')
        .sub(_rx(r'ناقل\s+الحركة'), 'الكمبيو')
        .sub(_rx(r'ناقل\s+حركة'), 'كمبيو')
        .sub(_rx(r'طنجرة\s+(القير|الجير)'), 'طنجرة الكمبيو (الكونفيرتا)')
        .sub(_rx(r'عقل\s+(القير|الجير)|مخ\s+(القير|الجير)'), 'عقل الكمبيو (الفالف بدي)')
        .sub(_rx(r'زيت\s+(القير|الجير)'), 'زيت الكمبيو')
        .sub(_rx(r'فلتر\s+(القير|الجير)'), 'فيلترو الكمبيو')
        .sub(_rx(r'مبرد\s+(القير|الجير)'), 'مبرد الكمبيو')
        .sub(_rx(r'حساس\s+(القير|الجير)|حساسات\s+(القير|الجير)'), 'حساس الكمبيو')
        .sub(_rx(r'كمبيوتر\s+(القير|الجير)'), 'كمبيوتر الكمبيو (TCM)')
        .sub(_rx(r'عصا\s+(القير|الجير)|ذراع\s+(القير|الجير)'), 'مارشا')
        // Definite: القير / الجير / الفتيس
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(قير|قاير|جير|فتيس)(?![\u0621-\u064A])'), r'$1كمبيو')
        // Plural: قيرات / جيرات
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)?(قيرات|جيرات)(?![\u0621-\u064A])'), 'كمبيوات')
        // Indefinite: قير / جير / فتيس
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(قير|قاير|جير|فتيس)(?![\u0621-\u064A])'), 'كمبيو');

    // 2. Fuel / Water / Oil Pump: طرمبة / طلمبة -> بومبة
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(طرمب|طلمب)(ة|ات)(?![\u0621-\u064A])'), r'$1بومب$3')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(طرمب|طلمب)ة(?![\u0621-\u064A])'), 'بومبة')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(طرمب|طلمب)ات(?![\u0621-\u064A])'), 'بومبات');

    // 3. Brake Pads: فحمات / قماشات / تيل فرامل -> باطنيات
    text = text
        .sub(_rx(r'تيل\s+الفرامل|أقمشة\s+الفرامل|فحمات\s+الفرامل'), 'باطنيات ديسكو')
        .sub(_rx(r'تيل\s+فرامل|أقمشة\s+فرامل|فحمات\s+فرامل'), 'باطنيات ديسكو');

    // 4. Control Arms: مقصات / مقص -> براتشوات / براتشو
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)مقصات(?![\u0621-\u064A])'), r'$1براتشوات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])مقصات(?![\u0621-\u064A])'), 'براتشوات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)مقص(?![\u0621-\u064A])'), r'$1براتشو')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])مقص(?![\u0621-\u064A])'), 'براتشو');

    // 5. Shock Absorbers: مساعدين / مساعدات -> مزاطوريات
    text = text
        .sub(_rx(r'مساعدات\s+الصدمات|ممتصات\s+الصدمات|مساعدين\s+الصدمات'), 'مزاطوريات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(مساعدين|مساعدات)(?![\u0621-\u064A])'), r'$1مزاطوريات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(مساعدين|مساعدات)(?![\u0621-\u064A])'), 'مزاطوريات')
        .sub(_rx(r'مساعد\s+(أمامي|خلفي|يمين|يسار)'), r'مزاطوري $1')
        .sub(_rx(r'المساعد\s+(الأمامي|الخلفي|الأيمن|الأيسر)'), r'المزاطوري $1');

    // 6. Axles / CV Joints: عكوس / عكس -> سمياصات / سمياص
    text = text
        .sub(_rx(r'جلدة\s+العكس|جلد\s+العكوس'), 'كرشيرة / قومة سمياص')
        .sub(_rx(r'رأس\s+العكس|رؤوس\s+العكوس'), 'رأس السمياص')
        .sub(_rx(r'عمود\s+العكس|أعمدة\s+العكوس'), 'عمود السمياص')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)عكوس(?![\u0621-\u064A])'), r'$1سمياصات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])عكوس(?![\u0621-\u064A])'), 'سمياصات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)عكس\s+(الأيمن|الأيسر|الأمامي|الخلفي|الداخلي|الخارجي)'), r'$1سمياص $2')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])عكس\s+(أيمن|أيسر|أمامي|خلفي|داخلي|خارجي)'), r'سمياص $1');

    // 7. Wheel Bearings: رمان بلي / صرة -> كوشينتي / موتسو
    text = text
        .sub(_rx(r'رمان\s+بلي\s+العجلة|رمان\s+بلي'), 'كوشينتي')
        .sub(_rx(r'الرمان\s+بلي'), 'الكوشينتي')
        .sub(_rx(r'صرة\s+العجلة'), 'موتسو العجلة');

    // 8. Timing Belt / Chain: سير تيمن / سير تايمن -> كاتينة
    text = text
        .sub(_rx(r'سير\s+(التا?يمن|التوقيت|الكاتينة)'), 'كاتينة')
        .sub(_rx(r'سير\s+(المحرك|المكينة|الدينمو)'), 'قايش المحرك');

    // 9. Exhaust: شكمان -> مرميطة
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)شكمان(?![\u0621-\u064A])'), r'$1مرميطة')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])شكمان(?![\u0621-\u064A])'), 'مرميطة')
        .sub(_rx(r'دبة\s+التلوث|محول\s+حفاز|المحول\s+الحفاز'), 'علبة كربون المرميطة');

    // 10. Radiator: رديتر / ردياتير / راديتر -> رداتوري
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(راديتر|ردياتير|رديتر)(?![\u0621-\u064A])'), r'$1رداتوري')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(راديتر|ردياتير|رديتر)(?![\u0621-\u064A])'), 'رداتوري');

    // 11. Starter: سلف -> موتورينو (مارش)
    text = text
        .sub(_rx(r'سلف\s+التشغيل|مارش\s+التشغيل'), 'موتورينو التشغيل')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)سلف(?![\u0621-\u064A])'), r'$1موتورينو')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])سلف(?![\u0621-\u064A])'), 'موتورينو');

    // 12. Oil Pan: كرتير / كارتير -> ستاقوبا
    text = text
        .sub(_rx(r'كرتير\s+الزيت|كارتير\s+الزيت'), 'ستاقوبا الزيت')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(كرتير|كارتير)(?![\u0621-\u064A])'), r'$1ستاقوبا')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(كرتير|كارتير)(?![\u0621-\u064A])'), 'ستاقوبا');

    // 13. Steering: دركسون / دركسيون -> ستيرسو / دومان
    text = text
        .sub(_rx(r'طارة\s+(الدركسون|الدركسيون)|عجلة\s+القيادة'), 'الدومان (الستيرسو)')
        .sub(_rx(r'دودة\s+(الدركسون|الدركسيون)|علبة\s+(الدركسون|الدركسيون)'), 'سكاتولة الستيرسو')
        .sub(_rx(r'زيت\s+(الدركسون|الدركسيون)'), 'زيت الستيرسو')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(دركسون|دركسيون)(?![\u0621-\u064A])'), r'$1ستيرسو')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(دركسون|دركسيون)(?![\u0621-\u064A])'), 'ستيرسو');

    // 14. Spark Plugs: بواجي / بوجيه -> شمعات / شمعة
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)(بواجي|بوجيهات)(?![\u0621-\u064A])'), r'$1شمعات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(بواجي|بوجيهات)(?![\u0621-\u064A])'), 'شمعات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)بوجيه(?![\u0621-\u064A])'), r'$1شمعة')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])بوجيه(?![\u0621-\u064A])'), 'شمعة');

    // 15. Ignition Coils: كويلات / كويل -> بوبينات / بوبينة
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)كويلات(?![\u0621-\u064A])'), r'$1بوبينات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])كويلات(?![\u0621-\u064A])'), 'بوبينات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)كويل(?![\u0621-\u064A])'), r'$1بوبينة')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])كويل(?![\u0621-\u064A])'), 'بوبينة');

    // 16. Fuel Injectors: بخاخات / بخاخ -> رشاشات / رشاش
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)بخاخات(?![\u0621-\u064A])'), r'$1رشاشات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])بخاخات(?![\u0621-\u064A])'), 'رشاشات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)بخاخ(?![\u0621-\u064A])'), r'$1رشاش')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])بخاخ(?![\u0621-\u064A])'), 'رشاش');

    // 17. Tires: كفرات -> قومّات
    text = text
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])(ال|بال|لل|فال|وال)كفرات(?![\u0621-\u064A])'), r'$1قومّات')
        .sub(_rx(r'(?<![\u0621-\u0647\u0649\u064A])كفرات(?![\u0621-\u064A])'), 'قومّات');

    // 18. Body: صدام -> براونطي, كبوت -> كوفنو
    text = text
        .sub(_rx(r'صدام\s+(أمامي|خلفي)'), r'براونطي $1')
        .sub(_rx(r'الصدام\s+(الأمامي|الخلفي)'), r'البراونطي $1')
        .sub(_rx(r'كبوت\s+السيارة|غطاء\s+المحرك'), 'كوفنو السيارة')
        .sub(_rx(r'شنطة\s+السيارة'), 'باقاج السيارة');

    // 19. Electrical Grounding: أرضية سيئة -> ضعف خط الماس/الأرضي
    text = text
        .replaceAll(
          _rx(r'وصلات\s+أرضية\s+سيئة|توصيل\s+أرضي\s+سيئ|تأريض\s+سيئ|أرضية\s+سيئة'),
          'ضعف خط الماس/الأرضي (صدأ أو ارتخاء برغي تأريض الشاسي)',
        )
        // 20. Bad/Loose Connection: اتصال سيئ -> ضعف تلامس كهربائي أو أكسدة في فيشة الحساس
        .replaceAll(
          _rx(r'اتصال\s+سي[ئء]|توصيل\s+سي[ئء]'),
          'ضعف تلامس كهربائي أو أكسدة في فيشة الحساس',
        );

    // 21. Cylinder / Piston: سلندر / مكبس -> بسطوني
    text = text
        .sub(_rx(r'حلقات\s+(ال)?مكبس|سنابر|سيجمانات'), 'شنابر')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(سلندرات|مكابس|بساتم)(?![ء-ي])'), r'$1بسطونات')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(سلندر|مكبس|بستم|بيستون|بستون)(?:اً|ا)?(?![ء-ي])'), r'$1بسطوني');

    // 22. Pumps: مضخة -> بومبة
    text = text
        .sub(_rx(r'مضخة\s+(ال)?توجيه(\s+المعزز)?'), 'بومبة ستيرسو')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?مضخ(ة|ات)(?![ء-ي])'), r'$1بومب$2');

    // 23. Brakes: مكابح -> فرامل, discs -> ديسكو
    text = text
        .sub(_rx(r'أقراص\s+(ال)?(فرامل|مكابح)'), 'ديسكوات')
        .sub(_rx(r'قرص\s+(ال)?(فرامل|مكابح)'), 'ديسكو')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?مكابح(?![ء-ي])'), r'$1فرامل')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(دبرياج|دبريج|قابض)(?![ء-ي])'), r'$1فرسيوني');

    // 24. Engine internals & electrical
    text = text
        .sub(_rx(r'رأس\s+(ال)?(محرك|سلندر)|راس\s+(ال)?محرك|سلندر\s+هيد'), 'التستاتا')
        .sub(_rx(r'كتلة\s+(ال)?(اسطوانات|أسطوانات|محرك)|بلوك\s+المحرك'), 'المونوبلوكو')
        .sub(_rx(r'ذراع\s+التوصيل|بيالة|بيله'), 'البيّلا')
        .sub(_rx(r'عمود\s+(ال)?(مرفق|كرنك)|كرنك\s+شافت'), 'الكولوا')
        .sub(_rx(r'عمود\s+(ال)?كامات|كامشافت'), 'الامبروكم')
        .sub(_rx(r'عجلة\s+(ال)?توازن|فلاي\s+ويل'), 'الفولانو')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(دينامو|مولد\s+(ال)?كهرباء|مولد\s+كهربائي|مولد)(?![ء-ي])'), r'$1دينمو')
        .sub(_rx(r'حشية\s+غطاء\s+(ال)?صمامات|جوان\s+غطاء\s+(ال)?صمامات'), 'قرسيوني الكوبيركو')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(حشية|جوان|حشوة)(?![ء-ي])'), r'$1قرسيوني')
        .sub(_rx(r'سبرنك|سبرنغات|نابض\s+حلزوني|يايات|ياي'), 'موليّات (سبرنقات)')
        .sub(_rx(r'ماص(ات)?\s+(ال)?صدمات'), 'مزاطوري');

    // 25. Filters: فلتر / مرشح -> فيلترو
    text = text
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(فلتر|فلاتر|مرشح)(?![ء-ي])'), r'$1فيلترو');

    // 26. Body, lights, interior
    text = text
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(مصباح|مصابيح)\s+(ال)?أمامي(ة)?'), r'$1فنار')
        .sub(_rx(r'لوحة\s+(ال)?عدادات|عداد\s+السرعة\s+والمؤشرات'), 'لوحة العدادات (الطبلون)')
        .sub(_rx(r'لوحة\s+(ال)?قيادة|داشبورد|داش\s+بورد'), 'الطبلون')
        .sub(_rx(r'ماسحات\s+(ال)?زجاج'), 'المساحات')
        .sub(_rx(r'مقبض\s+(ال)?باب'), 'مانيليا الباب')
        .sub(_rx(r'الإطار\s+الاحتياطي|إطار\s+احتياطي|الاستبن|استبن'), 'العجلة الاحتياط (السبير)')
        .sub(_rx(r'ماسورة\s+(ال)?عادم|أنبوب\s+(ال)?عادم|نظام\s+(ال)?عادم'), 'المرميطة')
        .sub(_rx(r'كاتم\s+(ال)?صوت|دبة\s+الرنين'), 'كاتم المرميطة')
        .sub(_rx(r'مفصل\s+(ال)?تعليق\s+(ال)?كروي|(ال)?جوزة\s+الكروية'), 'فوزيلي')
        .sub(_rx(r'رأس\s+ذراع\s+(ال)?توجيه|ذراع\s+(ال)?توجيه'), 'نوتشي')
        .sub(_rx(r'مفتاح\s+(ال)?ربط\s+(ال)?صليبة'), 'مفتاح كريك');

    // 27. Diagnostics: ECU -> كمبيوتر السيارة, Relays: كتاوت -> ريليه
    text = text
        .sub(_rx(r'وحدة\s+(ال)?تحكم\s+(ال)?إلكترونية|وحدة\s+(ال)?تحكم\s+(في\s+)?(ال)?محرك'), 'كمبيوتر السيارة')
        .sub(_rx(r'مرحل\s+كهربائي|المرحل\s+الكهربائي|(?<![ء-هىي])المرحل(?![ء-ي])'), 'الريلي')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?كتاوتات(?![ء-ي])'), r'$1ريليهات')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?كتاوت(?![ء-ي])'), r'$1ريليه');

    // 28. Words the AI invents or uses in formal Arabic / other dialects
    text = text
        .sub(_rx(r'(?<![ء-هىي])(ال)?(مذياع|مذيع)(?![ء-ي])'), r'$1راديو')
        .sub(_rx(r'(طقطوقة|طكاكة)(\s*/\s*(طقطوقة|طكاكة))?(\s+حزام\s+(ال)?أمان|\s+(ال)?شنتورة)?'), 'قفل حزام الأمان')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?شنتور[ةة](?![ء-ي])'), r'$1حزام أمان')
        // Idle speed: سلانسيه -> سيلانتي
        .sub(_rx(r'(?<![ء-هىي])(ال)?سلانسيه(?![ء-ي])'), 'السيلانتي (الوقوف)')
        // Tires: تواير -> قومات
        .sub(_rx(r'(?<![ء-هىي])(ال)?تواير(?![ء-ي])'), 'قومّات')
        // Wheels: جنط / جنوط -> ديسكو / ديسكوات
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?جنوط(?![ء-ي])'), r'$1ديسكوات')
        .sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?جنط(?![ء-ي])'), r'$1ديسكو')
        // Tire puncture shop: بنشر -> ورشة تصليح قومات
        .sub(_rx(r'(?<![ء-هىي])(ال)?بنشر(?![ء-ي])'), 'محل تصليح القومّات (البيلكانو)')
        // Engine knock: طرق المحرك / الصرقعة (Knock)
        .sub(_rx(r'دق\s+وتصفيق\s+(ال)?محرك|دق\s+وتصفيق'), 'طرق المحرك / الصرقعة (Knock)')
        .sub(_rx(r'(?<![ء-هىي])(ال)?صرقعة(?![ء-ي])'), 'طرق المحرك / الصرقعة (Knock)')
        // Spark plugs: شماعي -> شمعات
        .sub(_rx(r'(?<![ء-هىي])(ال)?شماعي(?![ء-ي])'), 'شمعات')
        // Radiator descaling: تسييخ -> تسليك وغسيل
        .sub(_rx(r'(?<![ء-هىي])(ال)?تسييخ(?![ء-ي])'), 'تسليك وغسيل')
        // Hoses: خرطوم / خراطيم -> مناكوطي / توبو
        .sub(_rx(r'خرطوم\s+(ال)?(ماء|مية|الرداتوري|تبريد)'), 'مناكوطي الرداتوري')
        .sub(_rx(r'خرطوم\s+(ال)?(هواء|فاكيوم|بوابة|شفط)'), 'توبو الهواء والفاكيوم')
        // Bearings: رمان بلي / البلية -> كوشينتي
        .sub(_rx(r'(?<![ء-هىي])(ال)?بلية(?![ء-ي])'), 'الكوشينتي')
        // Exhaust catalytic converter: دبة تلوث / دبة بيئة -> علبة كربون المرميطة
        .sub(_rx(r'دبة\s+(ال)?(تلوث|بيئة|البيئة)'), 'علبة كربون المرميطة');

    // 29. Chassis / VIN: شاسي / شاصي -> هيكل
    text = text.sub(_rx(r'(?<![ء-هىي])(ال|بال|لل|فال|وال)?(شاسيه|شاصيه|شاسي|شاصي)(?![ء-ي])'), r'$1هيكل');

    // Collapse "X (X)" left behind when a term and its gloss became identical.
    text = text.sub(
      _rx(r'([ء-ي][ء-ي ]*?)\s*\(\1\)'),
      r'$1',
    );

    return text;
  }
